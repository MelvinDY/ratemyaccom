/** Build a varied 5-photo gallery (exterior, bedroom, kitchen, lounge, study) offset per property. */
function gallery(i: number): string[] {
  const p = (arr: string[]) => arr[i % arr.length] as string;
  return [p(EXTERIOR), p(BEDROOM), p(KITCHEN), p(LOUNGE), p(STUDY)];
}
/** Gallery that swaps the last photo for an amenity shot (pool/gym) — for premium properties. */
function galleryPlus(i: number): string[] {
  return [...gallery(i).slice(0, 4), AMENITY[i % AMENITY.length] as string];
}

